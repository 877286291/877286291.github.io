def get_city_route(from_city, to_city):
    if from_city == to_city:
        return [from_city]
    routes = CITY_ROUTES.get(from_city, {})
    if to_city in routes:
        return routes[to_city]
    for start, dest_map in CITY_ROUTES.items():
        if to_city in dest_map:
            route = dest_map[to_city]
            if from_city in route:
                return route[route.index(from_city):]
    return None


